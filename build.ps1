# Builds the dashboard into a single self-contained HTML file.
#
# Why a single file: the dashboard is published as a Claude Artifact, whose
# Content-Security-Policy blocks every external fetch. No CDN, no web fonts,
# no image hosts, no data API. Everything - markup, styles, logic and the
# full dataset - has to arrive in one document. That constraint shapes the
# whole codebase: company marks are drawn procedurally on canvas rather than
# loaded as images, and typography uses system font stacks only.
#
# Inputs
#   dataset/*.csv       the entity data - themes, regions, hubs, backers,
#                       ventures, positions, rounds. The source of truth.
#                       Emitted into the page as `const DB`, column-oriented,
#                       every value a string; src/app.html types it on load.
#   src/data/*.js       reference configuration that is not tabular (role
#                       weights, niche rules, map outlines, listed exposure),
#                       as plain `const` declarations.
#   src/app.html        markup, CSS and application logic. Contains the marker
#                       /*__DATA__*/ where all of the above is injected.
#
# Outputs (git-ignored - regenerate rather than commit)
#   build/index.html        standalone page. Open this locally; it is also what
#                           GitHub Pages serves.
#   build/radar.body.html   content only, no document wrapper - this is what
#                           gets published as a Claude Artifact.
#
# The SQLite edition of the dataset is built separately by
# tools/build_sqlite.py, which also enforces the schema's keys.
#
# Usage:  .\build.ps1

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$app = Get-Content (Join-Path $here 'src\app.html') -Raw -Encoding UTF8

# Load order matters: ventures reference themes and hubs, positions reference
# ventures and backers. The app rebuilds its model in this order.
$tables = @('themes', 'regions', 'hubs', 'backers', 'ventures', 'positions', 'rounds')

$layers = @(
  'reference.js',   # role weights, graduated list, sectors, map outlines, exposure
  'niches.js'       # niche taxonomy, classification rules, exposure map
)

# JSON-style string literal. Escaped by hand rather than via ConvertTo-Json,
# whose array handling differs between Windows PowerShell 5.1 and pwsh 7.
# `<` is escaped so no value in the dataset can ever close the <script> tag.
function Quote([string]$s) {
  $sb = New-Object System.Text.StringBuilder ($s.Length + 2)
  [void]$sb.Append('"')
  foreach ($ch in $s.ToCharArray()) {
    switch ($ch) {
      '"'  { [void]$sb.Append('\"'); continue }
      '\'  { [void]$sb.Append('\\'); continue }
      '<'  { [void]$sb.Append('<'); continue }
      default {
        $c = [int]$ch
        if ($c -lt 0x20 -or $c -eq 0x2028 -or $c -eq 0x2029) { [void]$sb.Append(('\u{0:x4}' -f $c)) }
        else { [void]$sb.Append($ch) }
      }
    }
  }
  [void]$sb.Append('"')
  $sb.ToString()
}

$db = New-Object System.Text.StringBuilder
[void]$db.Append("/* Generated by build.ps1 from dataset/*.csv - edit the CSVs, not this. */`nconst DB = {`n")
$counts = @()
foreach ($t in $tables) {
  $path = Join-Path $here "dataset\$t.csv"
  if (-not (Test-Path $path)) { throw "Missing table: dataset\$t.csv" }
  $cols = (Get-Content $path -TotalCount 1 -Encoding UTF8).Trim() -split ','
  $rows = @(Import-Csv $path -Encoding UTF8)
  [void]$db.Append("  ${t}: {cols:[" + (($cols | ForEach-Object { Quote $_ }) -join ',') + "], rows:[`n")
  foreach ($r in $rows) {
    [void]$db.Append('    [' + (($cols | ForEach-Object { Quote $r.$_ }) -join ',') + "],`n")
  }
  [void]$db.Append("  ]},`n")
  $counts += "$t $($rows.Count)"
}
[void]$db.Append("};`n")

$parts = @($db.ToString())
foreach ($layer in $layers) {
  $path = Join-Path $here "src\data\$layer"
  if (-not (Test-Path $path)) { throw "Missing data layer: src\data\$layer" }
  $parts += Get-Content $path -Raw -Encoding UTF8
}
$data = $parts -join "`r`n"

if ($app -notmatch [regex]::Escape('/*__DATA__*/')) {
  throw "src\app.html is missing the /*__DATA__*/ marker - nowhere to inject the dataset."
}

# Literal replace, not -replace: the dataset contains $ and backslashes that a
# regex replacement would interpret as capture-group and escape syntax.
$body = $app.Replace('/*__DATA__*/', $data)

$outDir = Join-Path $here 'build'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText((Join-Path $outDir 'radar.body.html'), $body, $utf8)

$html = @"
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Pre-Consensus</title>
<style>*{margin:0}html,body{background:#080a12}</style>
</head>
<body>
$body
</body>
</html>
"@
$htmlPath = Join-Path $outDir 'index.html'
[System.IO.File]::WriteAllText($htmlPath, $html, $utf8)

$kb = [math]::Round((Get-Item $htmlPath).Length / 1KB)
Write-Host "Built build/index.html and build/radar.body.html ($kb KB)"
Write-Host "  tables: $($counts -join ' | ')"
